"""Write a byte-level patch file that turns the original Antanta.exe into the fixed one.

usage: python make_diff.py ORIGINAL.exe PATCHED.exe OUT.patch

Format (plain text, read by installer/install.ps1):
    # comments
    source-sha256 <hex>
    target-sha256 <hex>
    size <bytes>
    <file offset in hex> <replacement bytes in hex>
"""
import hashlib
import sys

src_path, dst_path, out_path = sys.argv[1:]
src = open(src_path, 'rb').read()
dst = open(dst_path, 'rb').read()
assert len(src) == len(dst), 'patched file must keep the original size'

# merge differing bytes into runs; gaps of up to 8 equal bytes are folded into a run
runs = []
i = 0
while i < len(src):
    if src[i] == dst[i]:
        i += 1
        continue
    start = end = i
    while end < len(src):
        if src[end] != dst[end]:
            end += 1
            continue
        gap = end
        while gap < len(src) and gap - end <= 8 and src[gap] == dst[gap]:
            gap += 1
        if gap < len(src) and gap - end <= 8 and src[gap] != dst[gap]:
            end = gap
        else:
            break
    runs.append((start, dst[start:end]))
    i = end

with open(out_path, 'w', newline='\n') as f:
    f.write('# The Entente Gold (Steam) - Windows 10/11 fix for Antanta.exe\n')
    f.write('# generated by tools/make_diff.py from tools/build_patched_exe.py + smooth60.py + text_overlay.py + fps_counter.py\n')
    f.write(f'source-sha256 {hashlib.sha256(src).hexdigest()}\n')
    f.write(f'target-sha256 {hashlib.sha256(dst).hexdigest()}\n')
    f.write(f'size {len(src)}\n')
    for off, data in runs:
        f.write(f'{off:x} {data.hex()}\n')
print(f'{len(runs)} runs, {sum(len(d) for _, d in runs)} bytes')
